DROP SCHEMA IF EXISTS med CASCADE;
CREATE SCHEMA med ;
SET search_path TO med ;

CREATE TABLE paziente (
  id_paziente CHAR(8) PRIMARY KEY,
  nome VARCHAR(30) NOT NULL,
  cognome VARCHAR(40) NOT NULL,
  data_nascita DATE,
  provincia_nascita CHAR(2),
  codice_asl CHAR(3),
  provincia_asl VARCHAR(2)
);

CREATE TABLE medico(
  id_medico INT PRIMARY KEY,
  nome VARCHAR(30) NOT NULL,
  cognome VARCHAR(30) NOT NULL,
  sesso CHAR(1),
  codice_asl CHAR(3),
  provincia_asl CHAR(2),
  indirizzo_ambulatorio VARCHAR(40)
);

CREATE TABLE visita (
  id_visita INT PRIMARY KEY,
  id_paziente CHAR(8) NOT NULL,
  id_medico INT NOT NULL,
  data DATE,
  peso NUMERIC(4,1), 
  altezza NUMERIC(3),
  pressione_minima NUMERIC(3),
  pressione_massima NUMERIC(3)
);

